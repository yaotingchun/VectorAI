// Helper to generate 24-hour realistic hourly UPH trend
const generateHourlyHistory = (targetUph: number, nominalUph: number, variancePercent: number = 0.08) => {
  const hours = [
    '00:00', '01:00', '02:00', '03:00', '04:00', '05:00',
    '06:00', '07:00', '08:00', '09:00', '10:00', '11:00',
    '12:00', '13:00', '14:00', '15:00', '16:00', '17:00',
    '18:00', '19:00', '20:00', '21:00', '22:00', '23:00'
  ];

  return hours.map((hour, idx) => {
    // Dip slightly during shift changeovers (06:00, 14:00, 22:00)
    const isShiftChange = hour === '06:00' || hour === '14:00' || hour === '22:00';
    const baseMult = isShiftChange ? 0.82 : 0.96 + (Math.sin(idx * 0.7) * variancePercent);
    const actualUph = Math.min(nominalUph, Math.round(targetUph * baseMult));
    const yieldPercent = parseFloat((98.0 + (Math.cos(idx * 0.5) * 1.2)).toFixed(1));
    const scrapUnits = Math.max(1, Math.round(actualUph * ((100 - yieldPercent) / 100)));

    return {
      hour,
      actualUph,
      targetUph,
      yieldPercent,
      scrapUnits,
    };
  });
};

